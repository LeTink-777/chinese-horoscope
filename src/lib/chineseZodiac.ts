export interface ChineseResult {
  name: string;
  birthYear: number;
  animal: AnimalName;
  animalIndex: number;
  chineseChar: string;
  element: ElementInfo;
  elementDescription: string;
  compatibility: CompatibilityInfo;
  year2026data: Year2026Data;
  yearOf2026: typeof YEAR_2026;
}

export function animalIndexFromYear(birthYear: number): number {
  return ((((birthYear - 4) % 12) + 12) % 12);
}

export function elementFromYear(birthYear: number): ElementInfo {
  const mod = ((((birthYear - 4) % 10) + 10) % 10);
  return ELEMENTS[ELEMENT_ORDER[Math.floor(mod / 2)]];
}

export function animalFromYear(birthYear: number): AnimalName {
  return ANIMALS[animalIndexFromYear(birthYear)];
}

/** Годы рождения знака для витрины на лендинге. */
export function yearsForAnimal(index: number, count = 4): number[] {
  const base = 1924 + index;
  return Array.from({ length: count }, (_, i) => base + 36 + i * 12);
}

export function calculateChinese(name: string, birthYear: number): ChineseResult {
  const animalIndex = animalIndexFromYear(birthYear);
  const animal = ANIMALS[animalIndex];
  const element = elementFromYear(birthYear);
  const compatibility = COMPATIBILITY_INFO[COMPATIBILITY_BY_ANIMAL[animal]];

  return {
    name,
    birthYear,
    animal,
    animalIndex,
    chineseChar: ANIMAL_CHARS[animalIndex],
    element,
    elementDescription: `${element.description} В сочетании со знаком «${animal}» это даёт тебе характер, который в 2026 году Змея считывает мгновенно.`,
    compatibility,
    year2026data: YEAR_2026_BY_ANIMAL[animal],
    yearOf2026: YEAR_2026,
  };
}

